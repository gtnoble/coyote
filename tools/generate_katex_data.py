#!/usr/bin/env python3
"""Generate complete data-only Ada KaTeX font metrics."""
import hashlib
import json
from decimal import Decimal
from pathlib import Path
import re
import sys

EXPECTED_SHA256 = "1e72fc6b451a565e60b1eb7e89f4738eb74f35edfcf3c9c273015700b42ae04d"
SOURCE_NAME = "KaTeX 0.16.22 src/fontMetricsData.js"
ALL_FACES = (
    "AMS-Regular", "Caligraphic-Bold", "Caligraphic-Regular",
    "Fraktur-Bold", "Fraktur-Regular", "Main-Bold", "Main-BoldItalic",
    "Main-Italic", "Main-Regular", "Math-BoldItalic", "Math-Italic",
    "SansSerif-Bold", "SansSerif-Italic", "SansSerif-Regular",
    "Script-Regular", "Size1-Regular", "Size2-Regular", "Size3-Regular",
    "Size4-Regular", "Typewriter-Regular")


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def ada_number(value):
    if isinstance(value, bool) or not isinstance(value, (int, Decimal)):
        raise ValueError(f"non-numeric metric: {value!r}")
    number = Decimal(value)
    if not number.is_finite():
        raise ValueError(f"non-finite metric: {value!r}")
    text = format(number, "f")
    whole, dot, fraction = text.partition(".")
    fraction = fraction.rstrip("0") or "0"
    groups = [fraction[index:index + 3] for index in range(0, len(fraction), 3)]
    return whole + "." + "_".join(groups)


def load_data(path):
    raw = Path(path).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise ValueError(f"source SHA-256 mismatch: {digest}")
    text = raw.decode("utf-8")
    marker = "export default "
    if not text.startswith("// This file is GENERATED by buildMetrics.sh. DO NOT MODIFY.\n" + marker):
        raise ValueError("unexpected fontMetricsData.js export wrapper")
    payload = text.split(marker, 1)[1].strip()
    if not payload.endswith(";"):
        raise ValueError("missing export terminator")
    payload = re.sub(r",\s*([}\]])", r"\1", payload[:-1])
    data = json.loads(payload, object_pairs_hook=unique_object,
                      parse_float=Decimal, parse_int=int,
                      parse_constant=lambda value: (_ for _ in ()).throw(
                          ValueError(f"non-finite JSON constant: {value}")))
    if not isinstance(data, dict) or len(data) != 18:
        raise ValueError("expected exactly 18 metric tables")
    if set(data) - set(ALL_FACES):
        raise ValueError("source contains an unrecognized face")
    for face, glyphs in data.items():
        if not re.fullmatch(r"[A-Za-z0-9]+-(?:Regular|Bold|Italic|BoldItalic)", face):
            raise ValueError(f"invalid face name: {face}")
        if not isinstance(glyphs, dict) or not glyphs:
            raise ValueError(f"empty/invalid glyph table: {face}")
        for point, metrics in glyphs.items():
            if not point.isdecimal() or not 0 <= int(point) <= 0x10FFFF:
                raise ValueError(f"invalid code point: {face}/{point}")
            if not isinstance(metrics, list) or len(metrics) != 5:
                raise ValueError(f"invalid metric tuple: {face}/{point}")
            for value in metrics:
                ada_number(value)
    return data, digest


def ada_face(face):
    return face.replace("-", "_")


def write_spec(path, faces):
    lines = [
        "--  Generated from KaTeX 0.16.22 src/fontMetricsData.js (MIT).",
        "--  Copyright (c) 2013-2020 Khan Academy and other contributors.",
        "--  See ../../share/coyote/math/licenses/KaTeX-MIT.txt and",
        "--  ../../share/coyote/math/PROVENANCE.md.",
        "package Math_Font_Data is",
        "   type Font_Face is", "     (" + ",\n      ".join(ada_face(f) for f in ALL_FACES) + ");",
        "", "   type Glyph_Metric is record",
        "      Found   : Boolean := False;",
        "      Width   : Long_Float := 0.0;",
        "      Ascent  : Long_Float := 0.0;",
        "      Descent : Long_Float := 0.0;",
        "      Italic  : Long_Float := 0.0;",
        "      Skew    : Long_Float := 0.0;", "   end record;",
        "", "   function Face_Stem (Face : Font_Face) return String;",
        "   function Asset_Filename (Face : Font_Face) return String;",
        "   function Lookup",
        "     (Face : Font_Face; Code_Point : Natural) return Glyph_Metric;",
        "end Math_Font_Data;", ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def write_body(path, data, digest):
    lines = [
        "--  GENERATED from KaTeX 0.16.22 src/fontMetricsData.js (MIT).",
        "--  Copyright (c) 2013-2020 Khan Academy and other contributors.",
        f"--  Source SHA-256: {digest}",
        "--  See ../../share/coyote/math/licenses/KaTeX-MIT.txt and",
        "--  ../../share/coyote/math/PROVENANCE.md.",
        "package body Math_Font_Data is", "",
        "   function Face_Stem (Face : Font_Face) return String is",
        "   begin", "      case Face is"]
    for face in ALL_FACES:
        lines += [f"         when {ada_face(face)} => return \"KaTeX_{face}\";"]
    lines += ["      end case;", "   end Face_Stem;", "",
              "   function Asset_Filename (Face : Font_Face) return String is",
              "   begin", "      return Face_Stem (Face) & \".ttf\";",
              "   end Asset_Filename;", "",
              "   function Lookup", "     (Face : Font_Face; Code_Point : Natural)",
              "      return Glyph_Metric", "   is", "   begin",
              "      case Face is"]
    for face in ALL_FACES:
        if face in data:
            glyphs = data[face]
            lines += [f"         when {ada_face(face)} =>",
                      "            case Code_Point is"]
        else:
            lines += [f"         when {ada_face(face)} =>",
                      "            return (others => <>);"]
            continue
        for point, (depth, height, italic, skew, width) in glyphs.items():
            values = ", ".join(ada_number(v) for v in
                                (width, height, depth, italic, skew))
            lines += [f"               when {int(point):,} =>".replace(",", "_"),
                      f"                  return (True, {values});"]
        lines += ["               when others =>",
                  "                  return (others => <>);",
                  "            end case;"]
    lines += ["      end case;", "   end Lookup;", "end Math_Font_Data;", ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def main():
    if len(sys.argv) != 4:
        raise SystemExit("usage: generate_katex_data.py SOURCE SPEC BODY")
    try:
        data, digest = load_data(sys.argv[1])
        write_spec(sys.argv[2], data)
        write_body(sys.argv[3], data, digest)
    except (OSError, UnicodeError, ValueError, json.JSONDecodeError) as error:
        raise SystemExit(f"error: {error}") from error
    print(f"source sha256={digest}")
    print(f"faces={len(data)} glyphs={sum(map(len, data.values()))}")
    print(f"generated {sys.argv[2]} and {sys.argv[3]}")


if __name__ == "__main__":
    main()
